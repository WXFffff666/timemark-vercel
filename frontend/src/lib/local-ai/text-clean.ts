/**
 * v2.28 批次 A：AI 输出净化（自然汉字，不是 markdown 文档）。
 *
 * 小模型（0.5B/1.7B）即使被提示词约束也常漏出 markdown 标记；屏显层是
 * whitespace-pre-wrap 裸文本，`##`/`**`/反引号会原样露出。这里做轻量清洗：
 * 去标记、保留换行与 [来源] 编号。只做确定性的标记剥离，不做任何"改写"。
 */

export function stripMarkdownLight(text: string): string {
  if (!text) return text;
  return (
    text
      // 代码围栏/行内反引号：去标记留内容
      .replace(/```[\w-]*\n?/g, '')
      .replace(/`([^`]+)`/g, '$1')
      // 标题行：去行首 #（1-6 个）+ 空格
      .replace(/^\s{0,3}#{1,6}\s+/gm, '')
      // 粗体/斜体：**x**、__x__、*x*（避免吃掉 [来源] 编号后的普通星号场景，仅成对剥离）
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/__([^_]+)__/g, '$1')
      .replace(/(^|[\s(（【])\*([^*\n]+)\*(?=[\s)）】.,!?;，。！？]|$)/g, '$1$2')
      // 无序列表前缀：行首 - / * / • + 空格（保留项内容）
      .replace(/^\s{0,4}[-•]\s+/gm, '')
      .replace(/^\s{0,4}\*\s+/gm, '')
      // 引用行前缀 "> "（周报综述等场景可能漏出）
      .replace(/^\s{0,3}>\s?/gm, '')
      // 图片/链接仅留文字：[文本](url) → 文本
      .replace(/!?\[([^\]]+)\]\([^)]*\)/g, '$1')
      // 表格分隔行整行删除；表格行内的 | 换成空格
      .replace(/^\s*\|?[\s:|-]+\|[\s:|-]*$/gm, '')
      .replace(/\|/g, ' ')
      // v2.35 R27（用户报告 mdx/md 残留）：
      // 水平线（--- 或 *** 独占一行）整行删除
      .replace(/^\s{0,3}([-*_][\s/]*){3,}$/gm, '')
      // 删除线 ~~x~~
      .replace(/~~([^~]+)~~/g, '$1')
      // 跨行拆散后残留的成对 **（全局兜底，无内容丢失——只去标记）
      .replace(/\*\*/g, '')
      // 行首孤立 #（无后缀的空标题）
      .replace(/^\s{0,3}#{1,6}\s*$/gm, '')
      // v2.39（用户再报"mdx 文档"）：mdx 文档头语句整行删——import/export 只会出现在
      // 模型吐 mdx 文档的场景，自然语言里没有以它们开头的行（区分大小写，只匹配语句）
      .replace(/^\s{0,3}(import|export)\s[^\n]*$/gm, '')
      // 模型偶尔漏出的 HTML/JSX 标签（<br> <b> <Card /> 等）剥标记；
      // 大写开头是 mdx/JSX 组件，小写是 HTML——一并剥离
      .replace(/<\/?[A-Za-z][^>]*>/g, '')
      // 行内跨行拆散后残留的孤立反引号（成对剥离之后剩奇数个的场景）
      .replace(/`/g, '')
      // 收尾：压掉 3+ 连续空行
      .replace(/\n{3,}/g, '\n\n')
      .trim()
  );
}
